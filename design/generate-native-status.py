#!/usr/bin/env python3
"""Bake the owner-selected 1.5x study into native 30px status artwork.

This authoring tool runs on the host, not the handheld or boot path. The
launcher draws the emitted dimensions directly; it never resizes these assets.
Legacy 20px artwork remains available for archived renderer checks.
"""
from pathlib import Path
import argparse,json,subprocess,tempfile
ROOT=Path(__file__).resolve().parent.parent
SOURCE=r'''
#include "battery.h"
#include "wifi.h"
#include "wifi-art.h"
#include <stdio.h>
static void array(const unsigned char *p,unsigned n){putchar('[');for(unsigned i=0;i<n;++i)printf("%s%u",i?",":"",p[i]);putchar(']');}
int main(void){unsigned char original[MP_BATTERY_PIXELS],empty[MP_BATTERY_SMALL_PIXELS],full[MP_BATTERY_SMALL_PIXELS];
mp_battery_art(0,100,original);mp_battery_small_art(original,empty);mp_battery_art(100,100,original);mp_battery_small_art(original,full);
printf("{\"empty\":");array(empty,sizeof empty);printf(",\"full\":");array(full,sizeof full);printf(",\"wifi\":");array(wifi_default_pixels,sizeof wifi_default_pixels);printf(",\"bands\":");array(wifi_default_bands,sizeof wifi_default_bands);puts("}");}
'''
def resize(values,width,height,out_width,out_height):
    return [values[min(height-1,y*2//3)*width+min(width-1,x*2//3)] for y in range(out_height) for x in range(out_width)]
def emit(name,values,width):
    rows=["    "+",".join(map(str,values[i:i+width]))+"," for i in range(0,len(values),width)]
    return f"static const uint8_t {name}[{len(values)}] = {{\n"+'\n'.join(rows)+"\n};\n"
def generated():
    with tempfile.TemporaryDirectory(prefix='minpocket-native-art-') as tmp:
        tmp=Path(tmp);(tmp/'art.c').write_text(SOURCE)
        subprocess.run(['cc','-std=c11','-O2','-I'+str(ROOT/'native'),str(tmp/'art.c'),str(ROOT/'native/battery.c'),'-o',str(tmp/'art')],check=True)
        data=json.loads(subprocess.check_output([str(tmp/'art')]))
    empty=resize(data['empty'],40,20,60,30);full=resize(data['full'],40,20,60,30)
    fill=[(i%60,i//60) for i in range(1800) if empty[i]!=full[i]]
    left=min(x for x,y in fill);right=max(x for x,y in fill)+1;top=min(y for x,y in fill);bottom=max(y for x,y in fill)+1
    assert set(fill)=={(x,y) for y in range(top,bottom) for x in range(left,right)}
    battery='/* SPDX-License-Identifier: GPL-2.0-only */\n/* Native 60x30 casing. Generated by design/generate-native-status.py. */\n'
    battery+=f'enum {{ BATTERY_NATIVE_FILL_X={left}, BATTERY_NATIVE_FILL_Y={top}, BATTERY_NATIVE_FILL_WIDTH={right-left}, BATTERY_NATIVE_FILL_HEIGHT={bottom-top} }};\n'
    battery+=emit('battery_native_casing',empty,60)
    wifi='/* SPDX-License-Identifier: GPL-2.0-only */\n/* Approved three-arc icon, native 47x30. Generated by design/generate-native-status.py. */\n'
    wifi+=emit('wifi_native_pixels',resize(data['wifi'],31,20,47,30),47)
    wifi+=emit('wifi_native_bands',resize(data['bands'],31,20,47,30),47)
    old=['.hfffffd','.hlffffm','..hffffm','..hlfffm','...hfffm','...hlffm','....hmmf','....ssss']
    cap=[''.join(old[y*2//3][x*2//3] for x in range(12)) for y in range(12)]
    moon='/* SPDX-License-Identifier: GPL-2.0-only */\n/* Native 12px Moonstone cap, authored from the chosen size study. */\n'
    moon+='static const char moonstone_native12[12][13] = {\n'+''.join('    "'+row+'",\n' for row in cap)+'};\n'
    return {'native/battery-native30-art.h':battery,'native/wifi-native30-art.h':wifi,'native/moonstone-native12.h':moon}
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,text in generated().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=text:parser.error(f'{name} differs from generated artwork')
        else:path.write_text(text)
if __name__=='__main__':main()
