#!/usr/bin/env python3
"""Compile the owner's selected sidebar icons into bounded native pixels."""
import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = root / 'design/themes/minpocket-default/navigation.json'
manifest = json.loads(source.read_text())
assert manifest['version'] == 1
rows = []
for item in manifest['items']:
    choice = {key: item[key] for key in ('name', 'icon', 'action')}
    pixels = item['pixels']
    assert len(pixels) == 16 and all(len(row) == 16 for row in pixels)
    assert all(type(value) is int and 0 <= value <= 4 for row in pixels for value in row)
    rows.append((choice, pixels))
assert [row[0]['name'] for row in rows] == [
    'Search', 'Home', 'Library', 'Favorites', 'Collections', 'Discovery', 'Settings']
abi = hashlib.sha256(json.dumps(rows, sort_keys=True).encode()).hexdigest()[:16]
out = ['/* SPDX-License-Identifier: GPL-2.0-only */',
       '/* Generated by design/compile-navigation.py; do not edit. */',
       '#ifndef MP_NAVIGATION_DEFAULT_H', '#define MP_NAVIGATION_DEFAULT_H',
       '#include <stdint.h>', f'#define MP_NAVIGATION_ABI UINT64_C(0x{abi})',
       'enum mp_navigation_item {',
       ' MP_NAV_SEARCH, MP_NAV_HOME, MP_NAV_LIBRARY, MP_NAV_FAVORITES,',
       ' MP_NAV_COLLECTIONS, MP_NAV_DISCOVERY, MP_NAV_SETTINGS, MP_NAV_COUNT',
       '};', '#ifdef MP_NAVIGATION_PIXELS',
       'static const struct mp_navigation_entry {',
       ' const char *name; enum mp_home_action action; uint8_t pixels[16][16];',
       '} mp_navigation[MP_NAV_COUNT] = {']
for choice, pixels in rows:
    out.append(' {"%s", %s, {' % (choice['name'], choice['action']))
    out.extend('  {' + ','.join(map(str, row)) + '},' for row in pixels)
    out.append(' }},')
out.extend(['};', '#endif', '#endif', ''])
result = '\n'.join(out)
parser = argparse.ArgumentParser()
parser.add_argument('--output', type=Path, default=root / 'native/navigation-default.h')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    assert args.output.read_text() == result, 'Regenerate navigation-default.h'
else:
    args.output.write_text(result)
